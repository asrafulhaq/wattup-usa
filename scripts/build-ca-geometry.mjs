/**
 * Generates lib/locations/ca-geometry.ts from US Census cartographic boundary data.
 *
 * The station finder section draws California as an inline SVG rather than a tiled
 * map: at state zoom the reference design is an illustration, not a slippy map, and
 * an SVG costs ~6 KB gzipped against ~230 KB for a WebGL map library. It also runs
 * on low end devices with no GPU context.
 *
 * Run: node scripts/build-ca-geometry.mjs
 * Source: US Census TIGER/Line cartographic boundaries (public domain).
 */
import { writeFileSync } from 'node:fs';

const SOURCE =
  'https://raw.githubusercontent.com/plotly/datasets/master/geojson-counties-fips.json';
const CA_STATE_FIPS = '06';
const VIEWBOX_WIDTH = 1000;
const SIMPLIFY_EPSILON = 0.8; // in viewBox units; 0.8 keeps coastline shape at ~17 KB
const OUT = 'lib/locations/ca-geometry.ts';
const OUT_GEO = 'lib/locations/ca-counties-geo.ts';
/** Simplification for the lng/lat copy, in degrees. About 1km at this latitude. */
const GEO_EPSILON = 0.01;

const ringsOf = (geometry) =>
  geometry.type === 'Polygon'
    ? geometry.coordinates
    : geometry.coordinates.flat();

const mercator = (lon, lat) => [
  (lon * Math.PI) / 180,
  Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360)),
];

/** Ramer-Douglas-Peucker. Drops points that sit within `epsilon` of the line they span. */
function simplify(points, epsilon) {
  if (points.length < 3) return points;
  const [ax, ay] = points[0];
  const [bx, by] = points[points.length - 1];
  const dx = bx - ax;
  const dy = by - ay;
  const span = Math.hypot(dx, dy);

  let furthest = -1;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i];
    const distance = span
      ? Math.abs(dy * px - dx * py + bx * ay - by * ax) / span
      : Math.hypot(px - ax, py - ay);
    if (distance > furthest) {
      furthest = distance;
      index = i;
    }
  }

  if (furthest <= epsilon) return [points[0], points[points.length - 1]];
  return [
    ...simplify(points.slice(0, index + 1), epsilon).slice(0, -1),
    ...simplify(points.slice(index), epsilon),
  ];
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`Source fetch failed: ${response.status}`);
const counties = (await response.json()).features.filter(
  (f) => f.properties.STATE === CA_STATE_FIPS,
);
if (counties.length !== 58) {
  throw new Error(`Expected 58 California counties, got ${counties.length}`);
}

// Projection bounds are derived from the geometry itself, then exported, so that
// markers projected at runtime land in the same space as these baked paths.
const projected = counties.flatMap((f) =>
  ringsOf(f.geometry).flatMap((ring) => ring.map(([lon, lat]) => mercator(lon, lat))),
);
const minX = Math.min(...projected.map((p) => p[0]));
const maxX = Math.max(...projected.map((p) => p[0]));
const minY = Math.min(...projected.map((p) => p[1]));
const maxY = Math.max(...projected.map((p) => p[1]));
const height = (VIEWBOX_WIDTH * (maxY - minY)) / (maxX - minX);

const toViewBox = (lon, lat) => {
  const [x, y] = mercator(lon, lat);
  return [
    ((x - minX) / (maxX - minX)) * VIEWBOX_WIDTH,
    ((maxY - y) / (maxY - minY)) * height,
  ];
};

const shapes = counties
  .map((feature) => {
    const d = ringsOf(feature.geometry)
      .map((ring) => {
        const simplified = simplify(
          ring.map(([lon, lat]) => toViewBox(lon, lat)),
          SIMPLIFY_EPSILON,
        );
        if (simplified.length < 3) return '';
        return `M${simplified.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}Z`;
      })
      .join('');
    return { name: feature.properties.NAME, fips: feature.properties.COUNTY, d };
  })
  .filter((c) => c.d)
  .sort((a, b) => a.name.localeCompare(b.name));

const file = `// Generated by scripts/build-ca-geometry.mjs. Do not edit by hand.
// Source: US Census TIGER/Line cartographic boundaries (public domain).
// ${shapes.length} counties, simplified at ${SIMPLIFY_EPSILON} viewBox units.

export type CountyShape = { name: string; fips: string; d: string };

/** Web Mercator bounds the paths below were projected against. */
export const CA_PROJECTION = {
  minX: ${minX},
  maxX: ${maxX},
  minY: ${minY},
  maxY: ${maxY},
  width: ${VIEWBOX_WIDTH},
  height: ${height.toFixed(2)},
} as const;

export const CA_COUNTIES: CountyShape[] = ${JSON.stringify(shapes, null, 2)};
`;

writeFileSync(OUT, file);

// A second copy in lng/lat, for drawing the same shapes on the WebGL map.
//
// The minimal view cannot use the basemap's own polygons: a vector style carries dozens
// of landuse and landcover fills at different shades, and with the labels stripped they
// read as blotchy noise rather than as the reference's clean, discrete regions. Drawing
// county shapes ourselves gives flat single tone blobs on an even field, which is what
// that design actually is.
const geoFeatures = counties.map((feature) => ({
  type: 'Feature',
  properties: {
    name: feature.properties.NAME,
    fips: feature.properties.COUNTY,
  },
  geometry: {
    type: 'MultiPolygon',
    coordinates: (feature.geometry.type === 'Polygon'
      ? [feature.geometry.coordinates]
      : feature.geometry.coordinates
    )
      .map((polygon) =>
        polygon
          .map((ring) => {
            const simplified = simplify(ring, GEO_EPSILON);
            return simplified.length >= 4 ? simplified.map(([lon, lat]) => [
              Number(lon.toFixed(4)),
              Number(lat.toFixed(4)),
            ]) : null;
          })
          .filter(Boolean),
      )
      .filter((polygon) => polygon.length > 0),
  },
})).filter((f) => f.geometry.coordinates.length > 0);

const geoFile = `// Generated by scripts/build-ca-geometry.mjs. Do not edit by hand.
// Source: US Census TIGER/Line cartographic boundaries (public domain).
//
// California counties in lng/lat, for the minimal map view. The basemap's own landuse
// and landcover fills read as blotchy noise once labels are stripped; these are flat,
// discrete shapes, which is what the reference design actually shows.

import type { FeatureCollection, MultiPolygon } from 'geojson';

export interface CountyProperties {
  name: string;
  fips: string;
}

export type CountyCollection = FeatureCollection<MultiPolygon, CountyProperties>;

export const CA_COUNTIES_GEO: CountyCollection = ${JSON.stringify(
  { type: 'FeatureCollection', features: geoFeatures },
)} as CountyCollection;
`;
writeFileSync(OUT_GEO, geoFile);
console.log(`${OUT_GEO}: ${geoFeatures.length} counties, ${(geoFile.length / 1024).toFixed(1)} KB`);

console.log(
  `${OUT}: ${shapes.length} counties, ${(file.length / 1024).toFixed(1)} KB`,
);
